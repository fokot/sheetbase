import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Marked} from 'marked';
import hljs from 'highlight.js/lib/core';
import typescript from 'highlight.js/lib/languages/typescript';
import bash from 'highlight.js/lib/languages/bash';
import json from 'highlight.js/lib/languages/json';
import {codeExamples} from '../assets/examples.mjs';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const out = path.join(root, '_site');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, content) => {
  const target = path.join(out, file);
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, content);
};
const escape = text => String(text).replace(/[&<>"']/g, char => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[char]));
hljs.registerLanguage('typescript', typescript);
hljs.registerLanguage('bash', bash);
hljs.registerLanguage('json', json);
const highlight = (text, language) => hljs.getLanguage(language)
  ? hljs.highlight(text, {language, ignoreIllegals: true}).value : escape(text);
const docs = [
  {source:'README.sk.md', output:'readme.html', lang:'sk', other:'en/readme.html', label:'README'},
  {source:'README.md', output:'en/readme.html', lang:'en', other:'readme.html', label:'README'},
  ...['API', 'ARCHITECTURE', 'TESTING', 'GOOGLE-SETUP'].flatMap(name => [
    {source:`docs/${name}.md`, output:`docs/${name}.html`, lang:'sk', other:`en/docs/${name}.html`, label:({API:'Referencia API', ARCHITECTURE:'Architektúra', TESTING:'Testovanie', 'GOOGLE-SETUP':'Google setup'})[name]},
    {source:`docs/en/${name}.md`, output:`en/docs/${name}.html`, lang:'en', other:`docs/${name}.html`, label:({API:'API reference', ARCHITECTURE:'Architecture', TESTING:'Testing', 'GOOGLE-SETUP':'Google setup'})[name]}
  ])
];
const destinations = new Map(docs.map(doc => [doc.source, doc.output]));
destinations.set('index.html', 'index.html');
destinations.set('en/index.html', 'en/index.html');
function relative(from, to) {
  return path.posix.relative(path.posix.dirname(from), to) || path.posix.basename(to);
}
function rewriteLinks(html, source, output) {
  return html.replace(/href="([^"#]+)(#[^"]*)?"/g, (match, href, hash = '') => {
    if (/^(?:[a-z]+:|\/\/)/i.test(href)) return match;
    const original = path.posix.normalize(path.posix.join(path.posix.dirname(source), href));
    const destination = destinations.get(original) ?? original;
    return `href="${escape(relative(output, destination))}${hash}"`;
  });
}
fs.rmSync(out, {recursive: true, force: true});
fs.mkdirSync(out, {recursive: true});
for (const directory of ['assets', 'dist', 'examples']) {
  fs.cpSync(path.join(root, directory), path.join(out, directory), {recursive: true});
}
const examples = Object.fromEntries(['sk','en'].map(lang => [lang, Object.fromEntries(
  Object.entries(codeExamples(lang === 'en')).map(([key, raw]) => [key, {raw, html:highlight(raw, 'typescript')}])
)]));
write('assets/code-examples.js', `// Generated by build:docs. No runtime highlighter dependency.\nexport const examples=${JSON.stringify(examples)};\n`);
for (const lang of ['sk','en']) {
  const source = lang === 'sk' ? 'index.html' : 'en/index.html';
  let html = rewriteLinks(read(source), source, source);
  const version = JSON.parse(read('package.json')).version;
  html = html.replace(/<span class="version">[^<]*<\/span>/, `<span class="version">${escape(version)}</span>`);
  html = html.replace(/(<pre id="exampleCode"[^>]*>)[\s\S]*?<\/pre>/, `$1<code class="hljs language-typescript">${examples[lang].connect.html}</code></pre>`);
  // Language switches point to directories and must retain their trailing slash.
  const alternate = lang === 'sk' ? 'en/' : '../';
  html = html.replace(/href="[^"]*" class="language-switch"/, `href="${alternate}" class="language-switch"`);
  write(source, html);
}
for (const doc of docs) {
  const en = doc.lang === 'en';
  const headings = [];
  const seen = new Map();
  const renderer = {
    heading({tokens, depth}) {
      const text = this.parser.parseInline(tokens);
      const base = text.replace(/<[^>]*>/g, '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'section';
      const index = seen.get(base) ?? 0; seen.set(base, index + 1);
      const id = base + (index ? `-${index}` : '');
      if (depth === 2) headings.push({id, text});
      return `<h${depth} id="${id}">${text}<a class="heading-anchor" href="#${id}" aria-label="${en?'Link to section':'Odkaz na sekciu'}">#</a></h${depth}>\n`;
    },
    code({text, lang}) {
      const language = (lang ?? 'text').split(/\s/)[0];
      return `<div class="doc-code"><div class="doc-code-bar"><span>${escape(language.toUpperCase())}</span><button type="button" data-copy-code aria-label="${en?'Copy code':'Skopírovať kód'}">${en?'Copy':'Kopírovať'}</button></div><pre><code class="hljs language-${escape(language)}">${highlight(text, language)}</code></pre></div>\n`;
    },
    table(token) { return `<div class="doc-table-wrap">${this.constructor.prototype.table.call(this, token)}</div>`; }
  };
  const markdown = new Marked({gfm:true, renderer});
  const content = rewriteLinks(markdown.parse(read(doc.source)), doc.source, doc.output);
  const asset = file => relative(doc.output, `assets/${file}`);
  const home = relative(doc.output, en?'en/index.html':'index.html');
  const nav = docs.filter(page => page.lang === doc.lang).map(page => `<a href="${relative(doc.output, page.output)}"${page.output===doc.output?' class="active" aria-current="page"':''}>${escape(page.label)}<span>↗</span></a>`).join('');
  const toc = headings.map(h => `<a href="#${h.id}">${h.text}</a>`).join('');
  write(doc.output, `<!doctype html>
<html lang="${doc.lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="description" content="Sheetbase — ${escape(doc.label)}"><title>${escape(doc.label)} — Sheetbase</title><link rel="icon" href="${asset('mark.svg')}" type="image/svg+xml"><link rel="stylesheet" href="${asset('site.css')}"></head>
<body class="docs-page"><a class="skip" href="#main">${en?'Skip to content':'Prejsť na obsah'}</a>
<header class="topbar"><a class="brand" href="${home}"><img src="${asset('mark.svg')}" alt="" width="30" height="30">sheetbase<span class="version">${escape(JSON.parse(read('package.json')).version)}</span></a><div class="top-actions"><a class="language-switch" data-language-switch href="${relative(doc.output, doc.other)}" lang="${en?'sk':'en'}" hreflang="${en?'sk':'en'}" aria-label="${en?'Prepnúť do slovenčiny':'Switch to English'}">${en?'SK':'EN'} ↔</a><a class="readme-link" href="https://github.com/fokot/sheetbase">GitHub ↗</a><button class="menu-button" aria-expanded="false" aria-controls="sidebar">Menu ☰</button></div></header>
<div class="layout"><aside class="sidebar" id="sidebar"><nav aria-label="${en?'Documentation':'Dokumentácia'}"><p class="nav-label">${en?'DOCUMENTATION':'DOKUMENTÁCIA'}</p><a href="${home}">${en?'Overview & demo':'Úvod a ukážka'}<span>←</span></a>${nav}<div class="nav-divider"></div><p class="nav-label">${en?'ON THIS PAGE':'NA TEJTO STRÁNKE'}</p><div class="document-toc">${toc}</div></nav></aside>
<main id="main" class="document-main"><div class="doc-breadcrumb"><a href="${home}">Sheetbase</a><span>/</span>${escape(doc.label)}</div><article class="document-content">${content}</article><footer class="doc-footer"><a href="https://github.com/fokot/sheetbase/blob/main/${doc.source}">${en?'View Markdown on GitHub':'Zobraziť Markdown na GitHube'} ↗</a><span>TypeScript · ESM · ${en?'No runtime dependencies':'Bez runtime závislostí'}</span></footer></main></div><script type="module" src="${asset('navigation.js')}"></script></body></html>`);
}
write('.nojekyll', '');
console.log(`Built bilingual documentation, ${docs.length} rendered Markdown pages, and highlighted examples → _site/`);
await import('./build-preview.mjs');
